describe('periodBrackets: the annual table divided by periods per year (unrounded)', () => {
  it('periods per year come from rates: 12 / 24 / 52 / 104 / 313', () => {
    expect(
      (['monthly', 'semi_monthly', 'weekly', 'twice_weekly', 'daily'] as const).map((f) =>
        periodsPerYear(f, RATES_V1),
      ),
    ).toEqual([12, 24, 52, 104, 313]);
  });
  it('semi-monthly second bracket starts at 250,000 ÷ 24 = 10,416.666… (not rounded)', () => {
    const b = periodBrackets('semi_monthly', RATES_V1)[1];
    expect(b?.over.startsWith('10416.6666666')).toBe(true);
    expect(b?.rate).toBe('0.15');
  });
  it('monthly fourth bracket: over 800,000 ÷ 12 = 66,666.67, base 102,500 ÷ 12 = 8,541.67', () => {
    const b = periodBrackets('monthly', RATES_V1)[3];
    expect(b && toMoney(b.over)).toBe('66666.67');
    expect(b && toMoney(b.base)).toBe('8541.67');
  });
});

