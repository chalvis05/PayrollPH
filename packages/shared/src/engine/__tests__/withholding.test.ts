describe('periodWithholding: every bracket boundary, all four divisors', () => {
  for (const [frequency, cases] of Object.entries(periodCases) as [
    PayFrequency,
    [string, string][],
  ][]) {
    it.each(cases)(`${frequency}: %s → %s`, (income, tax) => {
      expect(toMoney(periodWithholding(income, frequency, RATES_V1))).toBe(tax);
    });
  }

  it('zero and negative income → 0', () => {
    expect(toMoney(periodWithholding('0', 'semi_monthly', RATES_V1))).toBe('0.00');
    expect(toMoney(periodWithholding('-500', 'monthly', RATES_V1))).toBe('0.00');
  });

  it('reads periods per year from rates: monthly with n = 10 → bound 25,000', () => {
    const rates = ratesWith((r) => {
      r.bir.periodsPerYear = { ...r.bir.periodsPerYear, monthly: 10 };
    });
    // 0.15 × (26,000 − 25,000) = 150
    expect(toMoney(periodWithholding('26000', 'monthly', rates))).toBe('150.00');
  });
});

describe('annualize', () => {
  it('tax still payable: due 42,500 on 500,000, withheld 40,000 → balance +2,500', () => {
    const a = annualize({
      annualTaxableCompensation: '500000',
      taxWithheldYtd: '40000',
      rates: RATES_V1,
    });
    expect([a.taxDue, a.taxWithheld, a.balance].map(toMoney)).toEqual([
      '42500.00',
      '40000.00',
      '2500.00',
    ]);
  });
  it('refund: due 42,500, withheld 45,000 → balance −2,500', () => {
    const a = annualize({
      annualTaxableCompensation: '500000',
      taxWithheldYtd: '45000',
      rates: RATES_V1,
    });
    expect(toMoney(a.balance)).toBe('-2500.00');
  });
  it('below the exempt bracket: due 0, withheld 1,000 → refund 1,000', () => {
    const a = annualize({
      annualTaxableCompensation: '200000',
      taxWithheldYtd: '1000',
      rates: RATES_V1,
    });
    expect([a.taxDue, a.balance].map(toMoney)).toEqual(['0.00', '-1000.00']);
  });
  it('exactly withheld: 1,000,000 → due 152,500, withheld 152,500 → 0', () => {
    const a = annualize({
      annualTaxableCompensation: '1000000',
      taxWithheldYtd: '152500',
      rates: RATES_V1,
    });
    expect(toMoney(a.balance)).toBe('0.00');
  });
});
