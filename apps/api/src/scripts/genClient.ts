/**
 * Export the OpenAPI document and generate the web app's typed client types from it.
 *   pnpm --filter @payrollph/api gen:client
 * Writes apps/api/openapi.json and apps/web/src/api/schema.d.ts. No database connection is made.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { buildApp } from '../app';
import { configFromEnv } from '../config';
import { createDb } from '../db/client';

const apiRoot = resolve(import.meta.dirname, '../..');
const specPath = resolve(apiRoot, 'openapi.json');
const typesPath = resolve(apiRoot, '../web/src/api/schema.d.ts');

async function main(): Promise<void> {
  // postgres-js connects lazily, so building the app does not touch the database.
  const { db, sql } = createDb();
  const app = await buildApp({ db, config: configFromEnv() });
  await app.ready();
  const spec = app.swagger();
  await app.close();
  await sql.end();

  writeFileSync(specPath, `${JSON.stringify(spec, null, 2)}\n`);
  const ast = await openapiTS(JSON.parse(JSON.stringify(spec)));
  const header =
    '/* eslint-disable */\n// GENERATED by `pnpm --filter @payrollph/api gen:client`. Do not edit.\n';
  mkdirSync(dirname(typesPath), { recursive: true });
  writeFileSync(typesPath, header + astToString(ast));
  const paths = Object.keys((spec as { paths?: object }).paths ?? {}).length;
  console.log(`OpenAPI: ${paths} paths → ${specPath}\nTypes → ${typesPath}`);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
